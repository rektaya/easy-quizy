// Turns src/data/words.raw.txt into src/data/words.generated.ts.
// Run with: npm run build:words
import { readFileSync, writeFileSync } from 'node:fs';
import { CORE } from '../src/data/words.core.ts';

const RAW = new URL('../src/data/words.raw.txt', import.meta.url);
const OUT = new URL('../src/data/words.generated.ts', import.meta.url);

const slug = (lemma) =>
  lemma
    .toLowerCase()
    .replace(/ä/g, 'ae')
    .replace(/ö/g, 'oe')
    .replace(/ü/g, 'ue')
    .replace(/ß/g, 'ss')
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-|-$/g, '');

const fail = (msg) => {
  console.error(`build-words: ${msg}`);
  process.exit(1);
};

const themes = []; // { name, words: [...] }
const links = []; // [lemmaA, lemmaB]
let inLinks = false;

for (const [i, line] of readFileSync(RAW, 'utf8').split('\n').entries()) {
  const where = `words.raw.txt:${i + 1}`;
  if (!line.trim() || line.startsWith('#') && !line.startsWith('## ')) continue;
  if (line.startsWith('## ')) {
    inLinks = line.includes('Verbindungen');
    if (!inLinks) {
      const [name, english] = line.slice(3).split('|').map((x) => x.trim());
      if (!english) fail(`${where}: theme "${name}" needs an English name ("## Deutsch | english")`);
      themes.push({ name, english, words: [] });
    }
    continue;
  }
  if (line.startsWith('@ ')) {
    const [a, b] = line.slice(2).split('|').map((s) => s.trim());
    if (!a || !b) fail(`${where}: bad link "${line}"`);
    links.push([a, b, where]);
    continue;
  }
  const f = line.split('|');
  if (f.length !== 8) fail(`${where}: expected 8 fields, got ${f.length}: ${line}`);
  const [tier, article, lemma, plural, en, de, deEn, family] = f;
  if (!/^[1-6]$/.test(tier)) fail(`${where}: bad tier "${tier}"`);
  if (article && !['der', 'die', 'das'].includes(article)) fail(`${where}: bad article "${article}"`);
  if (!lemma || !en || !de || !deEn) fail(`${where}: missing field`);
  themes.at(-1).words.push({
    id: slug(lemma),
    tier: Number(tier),
    article: article || undefined,
    lemma,
    plural: plural || undefined,
    en,
    example: { de, en: deEn },
    family: family ? family.split(',').map((s) => s.trim()).filter(Boolean) : [],
    related: [],
    theme: themes.at(-1).name,
  });
}

const words = themes.flatMap((t) => t.words);
const coreById = new Map(CORE.map((w) => [w.id, w]));
const byId = new Map(words.map((w) => [w.id, w]));

for (const w of words) {
  if (coreById.has(w.id)) fail(`"${w.lemma}" is already a core word`);
}
if (byId.size !== words.length) {
  const seen = new Set();
  for (const w of words) {
    if (seen.has(w.id)) fail(`duplicate id "${w.id}"`);
    seen.add(w.id);
  }
}

// Same-theme links: the previous and next word, plus the first word one step up the
// difficulty ladder (or the nearest easier one at the very top), so every word has a
// way to travel to a harder or easier word within its theme.
for (const t of themes) {
  const ws = t.words;
  ws.forEach((w, i) => {
    let step = ws.findIndex((x) => x.tier > w.tier);
    if (step === -1) step = ws.findLastIndex((x) => x.tier < w.tier);
    const picks = [step, i + 1, i - 1, i + 2].filter((j) => j >= 0 && j < ws.length && j !== i);
    for (const j of picks) {
      if (w.related.length < 3 && !w.related.includes(ws[j].id)) w.related.push(ws[j].id);
    }
  });
}

// Cross-theme links, in both directions. Core words are named by lemma too.
const idOf = new Map([...CORE, ...words].map((w) => [w.lemma, w.id]));
const coreLinksBack = {}; // core id -> ids of generated words pointing at it
for (const [a, b, where] of links) {
  const ia = idOf.get(a);
  const ib = idOf.get(b);
  if (!ia) fail(`${where}: unknown word "${a}"`);
  if (!ib) fail(`${where}: unknown word "${b}"`);
  for (const [from, to] of [[ia, ib], [ib, ia]]) {
    if (byId.has(from)) {
      const w = byId.get(from);
      if (!w.related.includes(to)) w.related.push(to);
    } else {
      (coreLinksBack[from] ??= []).push(to);
    }
  }
}

const header = `// GENERATED by scripts/build-words.mjs from words.raw.txt. Do not edit by hand.
import type { RawWord } from './words';

export const GENERATED: RawWord[] = `;
writeFileSync(
  OUT,
  header +
    JSON.stringify(words, null, 2) +
    `;\n\n/** The themes of the generated words, in order, with the English name shown on the Map. */\nexport const THEMES: { id: string; de: string; en: string }[] = ` +
    JSON.stringify(themes.map((t) => ({ id: t.name, de: t.name, en: t.english })), null, 2) +
    `;\n\n/** Links from core words into the generated list, so the whole graph is one piece. */\nexport const CORE_LINKS: Record<string, string[]> = ` +
    JSON.stringify(coreLinksBack, null, 2) +
    ';\n',
);

const perTier = [1, 2, 3, 4, 5, 6].map((n) => words.filter((w) => w.tier === n).length);
console.log(`build-words: ${words.length} words in ${themes.length} themes; per tier ${perTier.join(' / ')}`);
