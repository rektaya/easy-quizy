#!/usr/bin/env python3
"""Step 9: the forms of every verb, for its card: "geht · ging · ist gegangen".

For each verb of the list (the meaning starts with "to") it takes, from the Wiktionary entry (the same cache as
the other steps, fetched from kaikki.org when a verb is not in it yet): the third person singular of the present, of
the past (Praeteritum), and the past participle with its auxiliary (hat / ist), as the dictionary spells them. A
separable verb carries its prefix ("steht auf · stand auf · ist aufgestanden"), a reflexive verb is looked up without
"sich". Where the dictionary gives two forms, the first is shown; where it allows both auxiliaries, "hat / ist".

Writes src/data/words.verbs.ts. Run after the word list changes: python3 scripts/words/verb_forms.py
"""
import json, os, re, sys
sys.path.insert(0, os.path.dirname(__file__))
from pick_lemmas import ROOT, fetch
from compose_raw import slug

AUX = {'haben': 'hat', 'sein': 'ist'}

# Wiktionary lists both auxiliaries for a verb that has one in the north and the other in the south of the German-speaking
# area, and for a verb whose auxiliary depends on the meaning. For the first kind the standard (northern) one is used here;
# the second kind keeps "hat / ist". A reflexive verb always takes "hat". (Checked by hand: change this list if a form looks wrong.)
STANDARD_AUX = {
    'anziehen': 'haben', 'aufstehen': 'sein', 'abfahren': 'sein', 'landen': 'sein', 'passieren': 'sein', 'schwimmen': 'sein', 'wandern': 'sein',
    'sitzen': 'haben', 'stehen': 'haben', 'liegen': 'haben',
}

def load_verbs():
    verbs = []  # (id, lemma as listed: with "sich " for a reflexive verb)
    for line in open(os.path.join(ROOT, 'src/data/words.raw.txt'), encoding='utf8').read().split('\n'):
        f = line.split('|')
        if len(f) == 8 and re.fullmatch(r'[1-6]', f[0]) and re.match(r'to\b', f[4].strip()):
            verbs.append((slug(f[2]), f[2]))
    core = open(os.path.join(ROOT, 'src/data/words.core.ts'), encoding='utf8').read()
    for m in re.finditer(r"id:\s*'([^']+)',\s*lemma:\s*'([^']+)',(?:\s*article:\s*'[^']*',)?(?:\s*plural:\s*'[^']*',)?\s*en:\s*'to\b", core):
        verbs.append((m.group(1), m.group(2)))
    return verbs

def pick(forms, *tags):
    return [f['form'] for f in forms if all(t in f.get('tags', []) for t in tags)]

def with_sich(form):
    """'zieht an' -> 'zieht sich an'; 'ernährt' -> 'ernährt sich'."""
    parts = form.split(' ')
    return ' '.join(parts[:1] + ['sich'] + parts[1:])

def forms_of(listed):
    reflexive = listed.startswith('sich ')
    lemma = listed[5:] if reflexive else listed
    for e in fetch(lemma):
        if e.get('lang_code') != 'de' or e.get('pos') != 'verb' or e.get('word') != lemma:
            continue
        fs = e.get('forms', [])
        present = pick(fs, 'present', 'third-person', 'singular', 'indicative')
        past = pick(fs, 'preterite', 'third-person', 'singular', 'indicative')
        part = pick(fs, 'participle', 'past')
        aux = []
        for a in pick(fs, 'auxiliary'):
            if a in AUX and a not in aux:
                aux.append(a)
        if present and past and part and aux:
            if reflexive:
                aux = ['haben']
            elif len(aux) > 1 and lemma in STANDARD_AUX:
                aux = [STANDARD_AUX[lemma]]
            have = ' / '.join(AUX[a] for a in aux)
            if reflexive:
                return [with_sich(present[0]), with_sich(past[0]), f'{have} sich {part[0]}']
            return [present[0], past[0], f'{have} {part[0]}']
    return None

def main():
    verbs = load_verbs()
    print('verbs:', len(verbs), flush=True)
    out, missing = {}, []
    for i, (wid, lemma) in enumerate(verbs):
        try:
            r = forms_of(lemma)
        except Exception as e:
            r = None
            print('error', lemma, e, flush=True)
        if r:
            out[wid] = r
        else:
            missing.append(lemma)
        if i % 50 == 0:
            print(i, flush=True)
    lines = [
        '// GENERATED by scripts/words/verb_forms.py. Do not edit by hand.',
        '// The forms of a verb, for its card: the third person singular of the present, of the past, and the perfect',
        '// (auxiliary and past participle), as Wiktionary spells them. [present, past, perfect]',
        'export const VERBS: Record<string, [string, string, string]> = {',
    ]
    for wid in sorted(out):
        lines.append(f"  {json.dumps(wid)}: {json.dumps(out[wid], ensure_ascii=False)},")
    lines.append('};')
    open(os.path.join(ROOT, 'src/data/words.verbs.ts'), 'w', encoding='utf8').write('\n'.join(lines) + '\n')
    print('written', len(out), 'verbs; without forms:', len(missing), missing[:30])

if __name__ == '__main__':
    main()
