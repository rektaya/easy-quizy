#!/usr/bin/env python3
"""Writes src/data/words.rank.ts: how common each word is (its place in the frequency list, 1 = most common).

Used by Explore's "usefulness" mode. A word the list does not know gets a place after the known words of its
tier. Run it after the words change: python3 scripts/words/rank_table.py
"""
import os, re, sys
sys.path.insert(0, os.path.dirname(__file__))
from pick_lemmas import ROOT, DATA, tier_of
from compose_raw import slug

def main():
    rank = {}
    for i, line in enumerate(open(os.path.join(DATA, 'de_50k.txt'), encoding='utf8')):
        rank.setdefault(line.split()[0], i + 1)
    entries = []  # (id, lemma, tier)
    for line in open(os.path.join(ROOT, 'src/data/words.raw.txt'), encoding='utf8').read().split('\n'):
        f = line.split('|')
        if len(f) == 8 and re.fullmatch(r'[1-6]', f[0]):
            entries.append((slug(f[2]), f[2], int(f[0])))
    core = open(os.path.join(ROOT, 'src/data/words.core.ts'), encoding='utf8').read()
    tiers = dict(re.findall(r"^\s*([a-z0-9-]+):\s*([1-6])\b", core.split('CORE_TIERS')[-1], re.M)) if 'CORE_TIERS' in core else {}
    for m in re.finditer(r"id:\s*'([^']+)',\s*lemma:\s*'([^']+)'", core):
        entries.append((m.group(1), m.group(2), int(tiers.get(m.group(1), 3))))
    # words that share their spelling with a more common word (Wolle / wollen) get their rank by hand: rank_overrides.txt, "lemma rank"
    overrides = {}
    path = os.path.join(os.path.dirname(__file__), 'rank_overrides.txt')
    if os.path.exists(path):
        for l in open(path, encoding='utf8'):
            if l.strip():
                lemma, _, n = l.strip().rpartition(' ')
                overrides[slug(lemma)] = int(n)
    # the words of the pilot (pilot_pick.py) come with the rank worked out from all their forms and their example: use it
    pilot_path = os.path.join(DATA, 'pilot.json')
    pilot = {}
    if os.path.exists(pilot_path):
        import json
        pilot = {slug(w['lemma']): w['rank'] for w in json.load(open(pilot_path, encoding='utf8'))}
    out = {}
    for wid, lemma, tier in entries:
        if wid in pilot and wid not in overrides:
            out[wid] = pilot[wid]
            continue
        if wid in overrides:
            out[wid] = overrides[wid]
            continue
        r = rank.get(lemma.casefold())
        if r is None and lemma.startswith('sich '):
            r = rank.get(lemma[5:].casefold())
        out[wid] = r if r is not None else 50000 + tier * 1000
    body = ',\n'.join(f"  '{k}': {v}" for k, v in sorted(out.items()))
    open(os.path.join(ROOT, 'src/data/words.rank.ts'), 'w', encoding='utf8').write(
        "// GENERATED by scripts/words/rank_table.py. Do not edit by hand.\n"
        "// How common each word is: its place in a frequency list of German (1 = the most common).\n"
        f"export const RANK: Record<string, number> = {{\n{body},\n}};\n")
    print('ranks for', len(out), 'words; unknown to the list:', sum(1 for v in out.values() if v >= 50000))

if __name__ == '__main__':
    main()
